#!/usr/bin/env python3
"""The engine's opcode stream, as data the machine can compare itself against.

If the trace cannot be got OUT of the machine reliably, the comparison can be done
INSIDE it: the expected stream ships in the .nex, the VM checks each record as it
produces it, and the only thing that crosses the boundary is a verdict - how many
matched, and the index of the first divergence. Two words instead of eight kilobytes.

That is a better shape for this gate anyway. A verdict read wrongly is a verdict
that disagrees with itself, and the checker can read it several times and from
several addresses; eight kilobytes read wrongly looks like a rasteriser bug.

    python3 tools/mkexpected.py preflight/hostprobe/probe/ops.txt build/expected_ops.inc
"""
import sys


def main():
    src = sys.argv[1] if len(sys.argv) > 1 else "preflight/hostprobe/probe/ops.txt"
    out = sys.argv[2] if len(sys.argv) > 2 else "build/expected_ops.inc"
    seed, recs = 0, []
    for line in open(src):
        f = line.split()
        if f[0] == "seed":
            seed = int(f[1]) & 0xFFFF
        elif f[0] == "thread":
            recs.append((2, int(f[3]), int(f[2])))
        elif f[0] == "op":
            recs.append((1, int(f[3]), int(f[4])))
    with open(out, "w") as fh:
        fh.write("; GENERATED by tools/mkexpected.py - do not edit.\n")
        fh.write("; The engine's own opcode stream, four bytes a record: kind, the\n")
        fh.write("; program counter as a word, then the opcode or the thread. Kind 1\n")
        fh.write("; is an opcode and kind 2 a thread edge, the same layout the VM\n")
        fh.write("; writes, so the comparison is a memcmp of four bytes at a time.\n")
        fh.write(f"EXPECTED_SEED   EQU {seed}\n")
        fh.write(f"EXPECTED_N      EQU {len(recs)}\n\nexpected_ops:\n")
        for k in range(0, len(recs), 4):
            for kind, pc, v in recs[k:k + 4]:
                fh.write(f"        db      {kind}\n        dw      {pc}\n"
                         f"        db      {v}\n")
    print(f"wrote {out}: {len(recs)} records, {len(recs)*4:,} bytes, seed {seed}")


if __name__ == "__main__":
    main()
