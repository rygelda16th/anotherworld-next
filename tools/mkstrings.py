#!/usr/bin/env python3
"""The string dictionary, from the reference's own table into something the Z80 can index.

drawString takes a string ID and walks _stringsTableEng until it matches or hits
END_OF_STRING_DICTIONARY (video.cpp:267-297, staticres.cpp:123). The table is C source, so
this parses it rather than transcribing it - a transcribed table is a table that drifts.

Emitted as a sorted index plus a blob, because the machine should binary-search rather than
walk 264 entries per string:

    str_index   two bytes of id, two of offset into the blob, sorted by id
    str_blob    the bytes, each run NUL-terminated, with \\n kept as-is because drawString
                treats it as a line break rather than a glyph (video.cpp:288)

    python3 tools/mkstrings.py preflight/hostprobe/probe/staticres.cpp build/strings.inc
"""
import re
import sys

ENTRY = re.compile(r'\{\s*(0x[0-9A-Fa-f]+)\s*,\s*"((?:[^"\\]|\\.)*)"\s*\}')

ESCAPES = {"n": "\n", "t": "\t", "\\": "\\", '"': '"', "0": "\0"}


def unescape(s):
    out, i = [], 0
    while i < len(s):
        if s[i] == "\\" and i + 1 < len(s):
            out.append(ESCAPES.get(s[i + 1], s[i + 1]))
            i += 2
        else:
            out.append(s[i])
            i += 1
    return "".join(out)


def main():
    src = sys.argv[1] if len(sys.argv) > 1 else "preflight/hostprobe/probe/staticres.cpp"
    out = sys.argv[2] if len(sys.argv) > 2 else "build/strings.inc"
    text = open(src, errors="replace").read()
    start = text.index("_stringsTableEng[]")
    end = text.index("};", start)
    body = text[start:end]

    seen, entries = {}, []
    for m in ENTRY.finditer(body):
        sid = int(m.group(1), 16)
        s = unescape(m.group(2))
        if sid in seen:
            continue                      # the reference's own table has no duplicates;
        seen[sid] = s                      # if one appears, the first wins as its walk does
        entries.append((sid, s))
    entries.sort()

    blob, offs = bytearray(), {}
    for sid, s in entries:
        offs[sid] = len(blob)
        blob += s.encode("latin-1", "replace") + b"\x00"

    longest = max(entries, key=lambda e: len(e[1]))
    nl = sum(1 for _, s in entries if "\n" in s)
    with open(out, "w") as fh:
        fh.write("; GENERATED by tools/mkstrings.py - do not edit.\n")
        fh.write(f"; {len(entries)} strings, {len(blob)} bytes of text. The index is sorted\n")
        fh.write("; by id so the machine can binary-search instead of walking the table the\n")
        fh.write("; way drawString does.\n")
        fh.write(f"STR_COUNT       EQU {len(entries)}\n")
        fh.write(f"STR_BLOB_LEN    EQU {len(blob)}\n\nstr_index:\n")
        for sid, _ in entries:
            fh.write(f"        dw      {sid}, {offs[sid]}\n")
        fh.write("\nstr_blob:\n")
        for i in range(0, len(blob), 24):
            chunk = ", ".join(str(b) for b in blob[i:i + 24])
            fh.write(f"        db      {chunk}\n")
    print(f"wrote {out}: {len(entries)} strings, {len(blob)} bytes of text, "
          f"{len(entries) * 4} of index")
    print(f"  longest is id {longest[0]:#05x} at {len(longest[1])} chars")
    print(f"  {nl} contain a newline, which drawString treats as a line break")
    bad = [c for _, s in entries for c in s if not (0x20 <= ord(c) < 0x80 or c == "\n")]
    if bad:
        print(f"  !! {len(bad)} characters outside the font's range: "
              f"{sorted(set(hex(ord(c)) for c in bad))}")


if __name__ == "__main__":
    main()
