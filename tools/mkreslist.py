#!/usr/bin/env python3
"""The resource table the game loads by: one entry a resource, from MEMLIST.BIN.

I3 needs the machine to answer, for a resource id the bytecode asks for, three
questions: what kind of thing is it, how big is it, and what is the file called. The
answers are all in MEMLIST and none of them are in the bytecode.

Four bytes an entry, so 146 resources cost 584 bytes:

    type      one byte, RT_* as resource.h:64-76 defines it. Type 6 is not in that
              enum and resource 0x11 uses it - the player-and-enemy polygon set every
              action part loads - so nothing may switch on type without a default.
    size      a word, the UNPACKED size, which is what the .BIN on the card holds
              because tools/mkassets.py unpacks at build time.
    pages     how many 8K pages that needs, precomputed so the machine does not
              divide.

The file name is derived rather than stored: PAL%02X for a palette, BMP%02X for a
full-screen bitmap, RES%02X for everything else, which is exactly what mkassets.py
writes.

    python3 tools/mkreslist.py data/ build/reslist.inc
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from memlist import entries, memlist_path  # noqa: E402

RT_POLY_ANIM, RT_PALETTE = 2, 3


def main():
    data = sys.argv[1] if len(sys.argv) > 1 else "data"
    out = sys.argv[2] if len(sys.argv) > 2 else "build/reslist.inc"
    es = list(entries(memlist_path(data)))
    n = len(es)
    big = [e for e in es if e["size"] > 0xFFFF]
    with open(out, "w") as fh:
        fh.write("; GENERATED by tools/mkreslist.py - do not edit.\n")
        fh.write(f"; {n} resources. Four bytes each: type, size as a word, pages.\n")
        fh.write(f"RES_COUNT       EQU {n}\n\nres_table:\n")
        for i, e in enumerate(es):
            size = min(e["size"], 0xFFFF)
            pages = (e["size"] + 8191) // 8192
            fh.write(f"        db      {e['type']}\n")
            fh.write(f"        dw      {size}\n")
            fh.write(f"        db      {pages}"
                     f"          ; {i:#04x} {e['size']:>6} bytes\n")
    kinds = {}
    for e in es:
        kinds[e["type"]] = kinds.get(e["type"], 0) + 1
    print(f"wrote {out}: {n} resources, {n * 4} bytes")
    print("  by type: " + ", ".join(f"{t}={c}" for t, c in sorted(kinds.items())))
    print(f"  largest {max(e['size'] for e in es):,} bytes, "
          f"{max((e['size'] + 8191) // 8192 for e in es)} pages")
    if big:
        print(f"  !! {len(big)} resources exceed a word and were clamped")


if __name__ == "__main__":
    main()
