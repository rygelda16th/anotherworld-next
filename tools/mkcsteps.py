#!/usr/bin/env python3
"""Cases for the calc_step unit test, and what they must produce.

calc_step is a signed 8x16 multiply, a two-bit shift and a 24-bit negate. A
fault in any of those looks from the outside exactly like a geometry fault, so it
is worth testing on its own: the cases below cover zero, positive and negative
runs, the extremes of both, and several rises including 1 and 0.
"""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from refvideo import INTERP, _s32

# p1 is deliberately NOT always zero. An earlier version of these cases used
# p1.x = 0 for every non-negative run and p1.y = 0 throughout, which made a bug
# that read p1 from a clobbered register indistinguishable from correct: zero is
# the one value that corruption and the truth agree on.
CASES = []
for p1y in (0, 7, 60, 130):
    for dy in (0, 1, 3, 5, 54, 118, 191):
        p2y = p1y + dy
        if not 0 <= p2y <= 255:
            continue
        for p1x in (0, 4, 90, 200):
            for dx in (0, 1, -1, 3, -3, 55, -55):
                p2x = p1x + dx
                if not 0 <= p2x <= 255:
                    continue
                CASES.append((p1x, p1y, p2x, p2y))

out_inc = sys.argv[1] if len(sys.argv) > 1 else "build/csteps.inc"
out_txt = sys.argv[2] if len(sys.argv) > 2 else "build/csteps.txt"
with open(out_inc, "w") as fh:
    fh.write("; GENERATED by tools/mkcsteps.py - do not edit.\n")
    fh.write(f"CS_COUNT        EQU {len(CASES)}\ncs_cases:\n")
    for a in CASES:
        fh.write(f"        db      {a[0]}, {a[1]}, {a[2]}, {a[3]}\n")
with open(out_txt, "w") as fh:
    for p1x, p1y, p2x, p2y in CASES:
        dy = (p2y - p1y) & 0xFFFF
        step = _s32((p2x - p1x) * INTERP[dy & 0x3FF] * 4)
        fh.write(f"{p1x} {p1y} {p2x} {p2y} {step & 0xFFFFFFFF} {dy}\n")
print(f"wrote {out_inc} and {out_txt}: {len(CASES)} cases")
