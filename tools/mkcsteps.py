#!/usr/bin/env python3
"""Cases for the calc_step unit test, and what they must produce.

calc_step is a signed multiply, a two-bit shift and a 32-bit negate. A fault in
any of those looks from the outside exactly like a geometry fault, so it is worth
testing on its own: the cases below cover zero, positive and negative runs, the
extremes of both, and several rises including 1 and 0.

**The coordinates are 16-bit.** They used to be bytes, and so did the multiply,
until the polygon reader needed a bounding box the game actually produces: over
the whole 64,897-polygon trace the post-zoom values reach 529 in x and 503 in y,
which is 423 and 483 after the 256x192 scale. A box wider than the screen is
legitimate data - the polygon is clipped - and the original is int16_t throughout.
So the cases now include values above 255 and runs longer than a byte, which is
what makes the widened 16x16 product testable rather than hopeful.
"""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from refvideo import INTERP, _s32

# p1 is deliberately NOT always zero. An earlier version of these cases used
# p1.x = 0 for every non-negative run and p1.y = 0 throughout, which made a bug
# that read p1 from a clobbered register indistinguishable from correct: zero is
# the one value that corruption and the truth agree on.
CASES = []
# Kept deliberately small. The cases and their expected results live in the 48K
# address space beside everything else, at fourteen bytes a case, and the first
# widened sweep produced 2,862 of them and pushed the program past 64K - which
# sjasmplus reported as "write outside of device memory" and three truncated
# address constants, not as "your test is too big".
for p1y in (0, 7, 130, 480):
    for dy in (0, 1, 3, 5, 191, 483):
        p2y = p1y + dy
        if not 0 <= p2y <= 1023:        # the interpolation table is 1024 entries
            continue
        for p1x in (0, 90, 300, 423):
            for dx in (0, 1, -1, 55, -55, 260, -260):
                p2x = p1x + dx
                if not 0 <= p2x <= 1023:
                    continue
                CASES.append((p1x, p1y, p2x, p2y))

out_inc = sys.argv[1] if len(sys.argv) > 1 else "build/csteps.inc"
out_txt = sys.argv[2] if len(sys.argv) > 2 else "build/csteps.txt"
with open(out_inc, "w") as fh:
    fh.write("; GENERATED by tools/mkcsteps.py - do not edit.\n")
    fh.write(f"CS_COUNT        EQU {len(CASES)}\n")
    fh.write("; Each case is TWO POINTS in the same layout poly_data uses: x and\n")
    fh.write("; y as signed words, so the self-test can point calc_step straight\n")
    fh.write("; at a case and exercise point_x and point_y with it.\n")
    fh.write("cs_cases:\n")
    for a in CASES:
        fh.write(f"        dw      {a[0]}, {a[1]}, {a[2]}, {a[3]}\n")
with open(out_txt, "w") as fh:
    for p1x, p1y, p2x, p2y in CASES:
        dy = (p2y - p1y) & 0xFFFF
        step = _s32((p2x - p1x) * INTERP[dy & 0x3FF] * 4)
        fh.write(f"{p1x} {p1y} {p2x} {p2y} {step & 0xFFFFFFFF} {dy}\n")
print(f"wrote {out_inc} and {out_txt}: {len(CASES)} cases")
