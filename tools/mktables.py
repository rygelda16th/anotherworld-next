#!/usr/bin/env python3
"""Generate the tables the rasteriser needs, as sjasmplus includes.

Only one table so far: the edge-step reciprocals. Video::init builds it as
_interpTable[0] = 0x4000 and _interpTable[i] = 0x4000 / i, and calcStep uses it
to turn a run over a rise into a 16.16 step without dividing:

    step = (x2 - x1) * interp[dy] * 4

Generated rather than computed at boot so there is exactly one definition of it,
and so the reference and the machine cannot drift - the same reason
wolf3d-next generates its tables instead of hand-writing them.
"""
import os
import sys

OUT = sys.argv[1] if len(sys.argv) > 1 else "build/interp.inc"
N = 0x400

os.makedirs(os.path.dirname(OUT) or ".", exist_ok=True)
vals = [0x4000] + [0x4000 // i for i in range(1, N)]
with open(OUT, "w") as fh:
    fh.write("; GENERATED by tools/mktables.py - do not edit.\n")
    fh.write(f"; {N} reciprocals: interp[0] = 0x4000, interp[i] = 0x4000 / i.\n")
    fh.write("; Indexed by a polygon edge's dy, so entry 0 is never a divide by\n")
    fh.write("; zero - the walk tests dy == 0 before it steps.\n")
    fh.write("interp_table:\n")
    for base in range(0, N, 8):
        row = ", ".join(f"${vals[base + k]:04X}" for k in range(8))
        fh.write(f"        dw      {row}\n")
    fh.write(f"        ASSERT $ - interp_table == {N * 2}\n")
print(f"wrote {OUT}: {N} entries, {N*2} bytes")
