"""The ten parts' resource lists, for I6's part transitions.

setupPart (resource.cpp:280) takes a part id in 0x3E80..0x3E89, subtracts GAME_PART_FIRST, and
reads four resource numbers out of memListParts: a palette, the bytecode, the cinematic
polygons, and a second polygon set that is 0x00 - MEMLIST_PART_NONE - for the parts that need
no player or enemy shapes (parts.h:26-32).

Read out of the reference's own table (parts.cpp) rather than retyped: forty numbers, and a
wrong one would send a part looking for somebody else's bytecode.

Every entry fits a byte, which the emitter asserts - our res_page table is indexed by a byte
everywhere, so a resource above 255 could not be reached even if one existed.
"""
import re
import sys


def table(src):
    m = re.search(r"memListParts\s*\[[^\]]*\]\s*\[4\]\s*=\s*\{(.*?)\n\};", src, re.S)
    if not m:
        raise SystemExit("memListParts not found in the reference")
    rows = []
    for line in m.group(1).splitlines():
        line = line.split("//")[0]
        vals = re.findall(r"0x([0-9A-Fa-f]+)", line)
        if len(vals) == 4:
            rows.append([int(v, 16) for v in vals])
    if len(rows) != 10:
        raise SystemExit(f"expected 10 parts, found {len(rows)}")
    return rows


def main():
    probe = sys.argv[1] if len(sys.argv) > 1 else "preflight/hostprobe/probe"
    out = sys.argv[2] if len(sys.argv) > 2 else "build/parts.inc"
    rows = table(open(f"{probe}/parts.cpp").read())
    for n, r in enumerate(rows):
        for v in r:
            if v > 0xFF:
                raise SystemExit(f"part {n} names resource {v:#06x}, which no byte holds")
    names = ["protection screens", "introduction cinematic", "", "", "",
             "battlechar cinematic", "", "", "", "password screen"]
    with open(out, "w") as fh:
        fh.write("; GENERATED by tools/mkparts.py - do not edit.\n")
        fh.write("; memListParts, parts.cpp: ten parts of four resources - palette, bytecode,\n")
        fh.write("; cinematic polygons, and a second polygon set that is zero where the part\n")
        fh.write("; needs no player or enemy shapes (MEMLIST_PART_NONE, parts.h:32).\n")
        fh.write("part_table:\n")
        for n, (pal, code, cin, vid2) in enumerate(rows):
            note = f"   ; part {n}" + (f", {names[n]}" if names[n] else "")
            fh.write(f"        db      ${pal:02X}, ${code:02X}, ${cin:02X}, ${vid2:02X}{note}\n")
    with2 = sum(1 for r in rows if r[3])
    print(f"  10 parts, 4 bytes each: {with2} name a second polygon set, "
          f"{10 - with2} do not")
    print(f"  written to {out}, 40 bytes")


if __name__ == "__main__":
    main()
