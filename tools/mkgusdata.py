#!/usr/bin/env python3
"""mkgusdata.py - plan-pi-gus.md's A1: the Pi card's files for this game, from nextpi-gus.

    python3 tools/mkgusdata.py NEXTPI_GUS build

nextpi-gus packs this game's sounds (its tools/sounds.py reads data/ through this repo's own
memlist.py and bytekiller.py, and its tools/mkupload.py packs them with the flac tool) and
builds its card installer; `make gus-assets` runs those first. This takes the results:

- build/assets/GUSALL.GUS   every sound's blocks and the table's, ready-made GUS1 upload lines
                            (227 blocks, numbered 0-226): what the boot sends
- build/assets/RES<id>.GUS  one sound's blocks: for the per-load mode, if the KS3 wants it
- build/assets/GUSINST.TXT  the card's installer, typed at SUP when the probe finds no card
- build/gusdata.inc         for the assembly: the blocks, the memory they fill, its CRC-32
                            (what %M must say), and each resource's address in the card's
                            memory (the W lines that zero a module instrument's first samples)
- src/inc/gus/gus.inc,      nextpi-gus's Next side, copied: the build container cannot see the
  src/inc/gus/piuart.inc,   other repo. Their cksums are pinned in gusdata.inc's header.
  src/inc/gus/gusprobe.inc  (gusprobe.inc for its probe line: the boot's own probe waits less)
- build/gusdata.inc also carries op_playSound's forty pitches in Hz (GUS_FREQ_HZ), the
  reference's own table (staticres.cpp, as tools/mksndfreq.py reads it), for the card's notes.

With no nextpi-gus build (NEXTPI_GUS/build/upload/aw missing), gusdata.inc says GUS_BLOCKS 0,
the assembly builds as ever, and the card is never tried: the Z80 path, unchanged. `make asm`
writes that file itself when there is none, so a fresh checkout assembles.

    python3 tools/mkgusdata.py NEXTPI_GUS BUILD [PROBE]      PROBE: preflight/hostprobe/probe
"""
import json
import os
import shutil
import subprocess
import sys
import zlib

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import mksndfreq  # noqa: E402

LINE = "; GENERATED by tools/mkgusdata.py from nextpi-gus - do not edit."


def cksum(path):
    r = subprocess.run(["cksum", path], capture_output=True, text=True, check=True)
    return " ".join(r.stdout.split()[:2])


def freq_macro(probe):
    """op_playSound's forty pitches, in Hz, as the reference has them (frequenceTable)."""
    hz = mksndfreq.table(open(os.path.join(probe, "staticres.cpp")).read())
    rows = ["        DW " + ", ".join(str(f) for f in hz[i:i + 10]) for i in range(0, 40, 10)]
    return ["; op_playSound's forty pitches in Hz: frequenceTable, staticres.cpp", "        MACRO GUS_FREQ_HZ"] + rows + [
        "        ENDM"]


def main(gus, build, probe="preflight/hostprobe/probe"):
    up_dir = os.path.join(gus, "build", "upload", "aw")
    inc = os.path.join(build, "gusdata.inc")
    os.makedirs(build, exist_ok=True)
    if not os.path.exists(os.path.join(up_dir, "upload.json")):
        open(inc, "w").write("\n".join([
            LINE, "; no nextpi-gus upload for this game: the card is never tried",
            "GUS_BLOCKS      EQU 0", "GUS_LEN_LO      EQU 0", "GUS_LEN_HI      EQU 0",
            "GUS_CRC_LO      EQU 0", "GUS_CRC_HI      EQU 0", "GUS_MEM_KB      EQU 1024",
            "        MACRO GUS_ADDR_TABLE", "        DS 146 * 3", "        ENDM"] + freq_macro(probe)) + "\n")
        print(f"{inc}: no nextpi-gus upload at {up_dir}: the card is off in this build")
        return
    up = json.load(open(os.path.join(up_dir, "upload.json")))
    image = open(os.path.join(up_dir, "card.img"), "rb").read()
    assets = os.path.join(build, "assets")
    os.makedirs(assets, exist_ok=True)
    files = [up["table"]["file"]] + [s["gus"] for s in up["sounds"]]
    with open(os.path.join(assets, "GUSALL.GUS"), "w") as out:
        for f in files:
            out.write(open(os.path.join(up_dir, f)).read())
    for s in up["sounds"]:
        shutil.copy(os.path.join(up_dir, s["gus"]), os.path.join(assets, s["gus"]))
    shutil.copy(os.path.join(gus, "build", "card", "GUSINST.TXT"), os.path.join(assets, "GUSINST.TXT"))
    os.makedirs("src/inc/gus", exist_ok=True)
    for f in ("gus.inc", "piuart.inc", "gusprobe.inc"):
        src = os.path.join(gus, "src", "next", f)
        text = open(src).read()
        head = (f";-----------------------------------------------------------------------------\n"
                f"; COPIED from nextpi-gus src/next/{f} by tools/mkgusdata.py (`make gus-assets`): the\n"
                f"; build container cannot see that repo. Do not edit here; change it there.\n")
        open(os.path.join("src/inc/gus", f), "w").write(head + text)
    addr = {s["id"]: s["address"] for s in up["sounds"]}
    rows = []
    for i in range(0, 146, 8):
        vals = [addr.get(j, 0) for j in range(i, min(i + 8, 146))]
        rows.append("        DB " + ", ".join(f"${a & 255:02X}, ${(a >> 8) & 255:02X}, ${a >> 16:02X}" for a in vals))
    crc = zlib.crc32(image) & 0xFFFFFFFF
    text = [
        LINE,
        f"; GUSALL.GUS {cksum(os.path.join(assets, 'GUSALL.GUS'))}; GUSINST.TXT {cksum(os.path.join(assets, 'GUSINST.TXT'))}",
        f"; gus.inc {cksum('src/inc/gus/gus.inc')}; piuart.inc {cksum('src/inc/gus/piuart.inc')}; "
        f"gusprobe.inc {cksum('src/inc/gus/gusprobe.inc')}",
        f"GUS_BLOCKS      EQU {up['blocks']}          ; GUSALL.GUS's blocks, 0 to {up['blocks'] - 1}",
        f"GUS_LEN_LO      EQU ${len(image) & 0xFFFF:04X}       ; the memory they fill: {len(image):,} bytes",
        f"GUS_LEN_HI      EQU ${len(image) >> 16:04X}",
        f"GUS_CRC_LO      EQU ${crc & 0xFFFF:04X}       ; its CRC-32, as %M says it",
        f"GUS_CRC_HI      EQU ${crc >> 16:04X}",
        f"GUS_MEM_KB      EQU {up['mem_kb']}",
        "; each resource's first sample in the card's memory, 3 bytes (0: not a sound)",
        "        MACRO GUS_ADDR_TABLE",
    ] + rows + ["        ENDM"] + freq_macro(probe)
    open(inc, "w").write("\n".join(text) + "\n")
    print(f"{inc}: {up['blocks']} blocks, {len(image):,} bytes, CRC-32 {crc:08X}; "
          f"{assets}/GUSALL.GUS {os.path.getsize(os.path.join(assets, 'GUSALL.GUS')):,} bytes, "
          f"GUSINST.TXT, {len(up['sounds'])} RES*.GUS; src/inc/gus/ copied")


if __name__ == "__main__":
    main(*sys.argv[1:4])
