"""op_playSound's frequency table, as the mixer's 8.8 increments.

snd_playSound hands the mixer `frequenceTable[freq]` (vm.cpp:716) and the mixer turns that
into a step with `chunkInc = (freq << 8) / sys->getOutputSampleRate()` (mixer.cpp:62) - 8.8
fixed point, source samples per output sample, which is exactly what our voices step in. Our
rate is the DAC's, and the DAC is written by the copper once a raster line: 312 lines at 50 Hz is
15,600 Hz. (It was the zxnDMA's prescalar 40, 21,875 Hz, until the copper took the DAC over.)

So the whole of op_playSound's pitch work is a forty-entry lookup, and no divide at runtime.
The forty frequencies come from the reference's own table at staticres.cpp:61-67 rather than
being retyped here - a wrong digit in a table of forty is invisible, and the file is GPL and
present in the tree.

The truncation matches the reference's: C integer division, so floor.
"""
import re
import sys

RATE = 312 * 50                         # 15,600 Hz: one copper MOVE a raster line


def table(src):
    m = re.search(r"frequenceTable\[\]\s*=\s*\{(.*?)\}", src, re.S)
    if not m:
        raise SystemExit("frequenceTable not found in the reference")
    vals = [int(v, 16) for v in re.findall(r"0x([0-9A-Fa-f]+)", m.group(1))]
    if len(vals) != 40:
        raise SystemExit(f"expected 40 frequencies, found {len(vals)}")
    return vals


def main():
    probe = sys.argv[1] if len(sys.argv) > 1 else "preflight/hostprobe/probe"
    out = sys.argv[2] if len(sys.argv) > 2 else "build/sndfreq.inc"
    freqs = table(open(f"{probe}/staticres.cpp").read())
    incs = [(f << 8) // RATE for f in freqs]
    with open(out, "w") as fh:
        fh.write("; GENERATED by tools/mksndfreq.py - do not edit.\n")
        fh.write("; op_playSound's forty pitches as 8.8 increments at "
                 f"{RATE} Hz.\n")
        fh.write("; frequenceTable, staticres.cpp:61-67; (freq << 8) / rate, mixer.cpp:62.\n")
        fh.write("snd_freq:\n")
        for i in range(0, 40, 8):
            row = ", ".join(str(v) for v in incs[i:i + 8])
            fh.write(f"        dw      {row}\n")
    lo, hi = min(incs), max(incs)
    print(f"  40 pitches, {freqs[0]:#06x}..{freqs[-1]:#06x} Hz -> increments {lo}..{hi} "
          f"({lo / 256:.3f}..{hi / 256:.3f} samples an output sample)")
    # the reference asserts freq < 40 (vm.cpp:714); nothing here can exceed the table
    print(f"  written to {out}, {40 * 2} bytes")


if __name__ == "__main__":
    main()
